#[cfg(test)]
mod tests {
    use super::*;

    /// The headers are shown through a variable, which the catalogue's scanner cannot see.
    #[test]
    fn category_names_are_translated() {
        for c in CATEGORIES {
            assert!(
                texcraft_i18n::has(texcraft_i18n::Lang::ZhHans, c.name),
                "{:?}",
                c.name
            );
        }
    }
}
